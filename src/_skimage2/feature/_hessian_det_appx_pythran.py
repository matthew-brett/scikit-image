# Changes from dlib:
#
# - one lobe from `sigma`, rather than a pyramid of octaves and intervals;
# - every pixel is computed, rather than leaving a border;
# - `_sum_of_area` clips each rectangle to the image, so pixels outside the
#   image count as zero, where dlib's `get_sum_of_area` requires the
#   rectangle to be inside the image;
# - the determinant is returned as is, without dlib's clamp of negative
#   values to zero;
# - the determinant is not multiplied by the sign of the Laplacian.

import numpy as np


def _centered_rect(r, c, height, width):
    """Rectangle of `height` rows and `width` columns centred on ``(r, c)``.

    As dlib's ``centered_rect``. Returns ``(top, left, bottom, right)``, with
    ``bottom`` and ``right`` inclusive. For odd sizes the rectangle is
    symmetric about ``(r, c)``.
    """
    top = r - height // 2
    left = c - width // 2
    return top, left, top + height - 1, left + width - 1


def _sum_of_area(img, top, left, bottom, right):
    """Sum of the image over a rectangle, counting zero outside the image.

    `img` is the integral image of the image to sum, with ``img[i, j]`` the
    sum of the image over rows ``0 .. i`` and columns ``0 .. j``. The
    rectangle is ``(top, left, bottom, right)``, inclusive, as from
    `_centered_rect`. dlib's ``get_sum_of_area`` requires the rectangle to be
    inside the image; here it is first clipped to the image, which is the
    same as counting zeros outside.
    """
    top = max(top, 0)
    left = max(left, 0)
    bottom = min(bottom, img.shape[0] - 1)
    right = min(right, img.shape[1] - 1)
    if top > bottom or left > right:
        return 0.0
    top_left = img[top - 1, left - 1] if top > 0 and left > 0 else 0.0
    top_right = img[top - 1, right] if top > 0 else 0.0
    bottom_left = img[bottom, left - 1] if left > 0 else 0.0
    return img[bottom, right] - bottom_left - top_right + top_left


def _centered_sum(img, r, c, height, width):
    """`_sum_of_area` over `_centered_rect`."""
    top, left, bottom, right = _centered_rect(r, c, height, width)
    return _sum_of_area(img, top, left, bottom, right)


# pythran export _surf_lobe(float or int)
def _surf_lobe(sigma):
    """The SURF lobe for `sigma`: the odd integer nearest to `sigma`.

    A `sigma` halfway between two odd integers, such as 2 or 4, rounds up.
    The lobe is at least 1.
    """
    return 2 * int(max(sigma, 0) / 2) + 1


# pythran export _hessian_matrix_det(float64[:,:], float or int)
def _hessian_matrix_det(img, sigma):
    """Compute the approximate Hessian Determinant over a 2D image.

    This method uses box filters over integral images to compute the
    approximate Hessian Determinant as described in [1]_. The filters and
    their layout follow dlib's ``hessian_pyramid`` [2]_.

    Parameters
    ----------
    img : array
        The integral image over which to compute Hessian Determinant.
    sigma : float
        Sets the lobe ``L`` of the box filters, the odd integer nearest to
        `sigma` (see `_surf_lobe`). The filters are ``3 L`` pixels wide.

    Returns
    -------
    out : array
        The array of the Determinant of Hessians.

    References
    ----------
    .. [1] Herbert Bay, Andreas Ess, Tinne Tuytelaars, Luc Van Gool,
           "SURF: Speeded Up Robust Features"
           ftp://ftp.vision.ee.ethz.ch/publications/articles/eth_biwi_00517.pdf
    .. [2] dlib, ``dlib/image_keypoint/hessian_pyramid.h``,
           https://github.com/davisking/dlib

    Notes
    -----
    The running time of this method only depends on size of the image. It is
    independent of `sigma` as one would expect.

    The filters are centred on each pixel, and sum to zero, so a constant or
    a linear ramp gives zero inside the image. Pixels outside the image count
    as zero.
    """
    lobe_size = _surf_lobe(sigma)
    area_inv = 1.0 / (3.0 * lobe_size) ** 2
    # Centres of the four Dxy boxes, as offsets from the pixel; each box is
    # one pixel clear of the centre row and column.
    lobe_offset = lobe_size // 2 + 1
    height, width = img.shape
    out = np.empty_like(img, dtype=np.float64)

    for r in range(height):
        for c in range(width):
            # Second derivative across the columns: a box 3 L wide minus
            # three times its middle lobe, so the lobes weigh 1, -2, 1.
            Dxx = _centered_sum(
                img, r, c, 2 * lobe_size - 1, 3 * lobe_size
            ) - 3.0 * _centered_sum(img, r, c, 2 * lobe_size - 1, lobe_size)
            # The same down the rows.
            Dyy = _centered_sum(
                img, r, c, 3 * lobe_size, 2 * lobe_size - 1
            ) - 3.0 * _centered_sum(img, r, c, lobe_size, 2 * lobe_size - 1)
            # Mixed derivative: the bottom-left and top-right boxes minus the
            # top-left and bottom-right. Its sign does not matter, because
            # the determinant uses its square.
            Dxy = (
                _centered_sum(
                    img, r + lobe_offset, c - lobe_offset, lobe_size, lobe_size
                )
                + _centered_sum(
                    img, r - lobe_offset, c + lobe_offset, lobe_size, lobe_size
                )
                - _centered_sum(
                    img, r - lobe_offset, c - lobe_offset, lobe_size, lobe_size
                )
                - _centered_sum(
                    img, r + lobe_offset, c + lobe_offset, lobe_size, lobe_size
                )
            )
            Dxx *= area_inv
            Dyy *= area_inv
            Dxy *= area_inv
            out[r, c] = Dxx * Dyy - 0.81 * Dxy * Dxy

    return out
